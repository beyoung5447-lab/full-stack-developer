/* 오라클의 형변환 함수
오라클 데이터베이스에서  형변환 함수는 서로 다른 데이터 타입간의 상호 변환을 수렴하는
필수적인 도구입니다. 데이터베이스는 연산이나 비교를 수행할 때 데이터 타입이 일치해야 하므로
타입 불일치로 인한 에러를 방지하고 원하는 포맷으로 데이터를 가공 및 출력하기 위해 반드시 사용됩니다.    
사용자가 함수를 통해 명확하게 타입을 지정해 주는 방식을 사용하여 데이터의 무결성과 쿼리의 안전성을 
확보 합니다. 
핵심 키워드
명시적 형변환: 개발자가 to_char,to_number,to_date등의 형변환 함수를 직접 사용하여
의도적으로 데이터 타입을 변환하는 방식입니다. 
암시적 형변환: 오라클 db 엔진이 쿼리 실행시 자동으로 타입을 변환하는 현상입니다.
포맷 모델: 변환 과정에서 데이터의 형태를 결정하는 규칙입니다.
nls 파라미터: 국가별 언어, 기호, 통화등 지역화된 형식을 결정하는 설정값입니다.
주요 형변환 함수 3총사 상세
숫자형 변환 함수: to_number()
문자열 데이터를 숫자 타입으로 변환하여 산술 연산이나 크기 비교가 가능하게 합니다.
기본 구문: to_number,nls_param
활용: 통화 기호나 천 단위 콤마가 포함된 문자열 데이터를 실제 계산 가능한 숫자 데이터로
바꿀 때 주로 사용합니다. 숫자나 날짜 데이터를 문자열 타입으로 변환 합니다. 오라클에서
가장 활용도가 높은 형변환 함수입니다. 기본 구문: to_char(), format 형식, nls_param
활용: 날짜를 특정 양식으로 출력 하거나 숫자에 천 단위 구분 기호를 표기하는 화면 출력을
데이터 포맷팀에 핵심적으로 사용됩니다.
날짜형 변환 함수: to_date()
문자열 데이터를 날짜 타입으로 변환 합니다.
기본 구문: to_date
활용: 사용자나 외부 시스템으로부터 입력 받은 문자열, 날짜간의 계산이나
특정 기간 조회를 가능하게 합니다.
to_cat()
문자열로 변환하여 처리해주는 유형을 말합니다.
유형
날짜 데이터 ==> 문자열
  to_char(날짜유형데이터,형식)
  해당 형식으로 사용되는 속성값
  to_char(날짜데이터,'yyyy/mm/dd q am/pm hh24:mi:ss')
  yyyy: 연도를 추출해서 출력해준다. yyy,yy 형식도 존재
  q: 분기 1/4분기에서 4/4q 분기 1~4로 문자열로 표현
  month: 월을 표현, mon, mm으로 축약해서 보여주기도 한다
  ww: 열단위 주, 1년에 52주 기눈
  w: 월단위 주, 1주차, 5주차등
  dd: 일
  day: 요일
  am/pm: 오전/오후 표시 하나만 표현해도 된다 am이든 pm이든
  hh: 12시간 표현
  hh24: 24 시간 표현
  mi: 분표시
  ss: 초표시
  위 내용 하나 또는 여러개로 사용하여 쓰기도 하고 중간에 구분 문자열을
  선언해서 사용 하기도 한다. 
  중간에 정의한 특수 문자를 넣어서 구분할려면 표현할 내용과 함께 사용하기도 한다.

