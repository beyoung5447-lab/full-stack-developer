/*1:N 관계 실습예제
1:N 관계는 엔티티 타임간에 여러 경우에 사용되는 가장 대표적인 관계
한사람이 소유한 여러가지 물건 보호자 한명에 반려동물 한사람이 수강신청한 수강과목등과 같이
대부분의 관계다
요구 사향: 동물병원에서 보호자 한명은 여러 마리의 반려동물 등록 가능
하지만 병원 기록상 한 마리의 반려동물은 오직 한명의 대표 보호자 밑에만 소속
개념적 모델링(안티티, 속성, 관계)
앤티티: 보호자, 반려동물
속성: 보호자(보호자번호, 이름, 연락처)
반려동물(동물번호, 이름, 종등
관계: 보호자와 반려동물은 1:N 관계이다)
논리적 모델링 설계
구체적으로 사용할 컬럼명/속성을 지정(물리적 모델로 가기위해)
관계 형식 지정 1:N 관계에서 무조건 N(여러개) 쪽에 1은 번호(FK)를 달아줍니다.(툴을 통해서 자동화) 
        ex) 보호자 1명의 칸에 강아지 5마리의 이름을 다 적을 수 없으니, 강아지 5마리의 목걸이에
        각각 우리 집사는 1번 보호자야!라고 명찰(FK)을 달아주는 원리입니다.
        보호자(1의 입장, 부모 테이블), PK = 보호자 번호
        반려동물(N의 입장, 자식 테이블), PK = 동물번호 / FK = 보호자번호(보호자 참조)
        문제 1: 학교의 '반(Class)'과 '학생들'
요구사항: 한 개의 [반]에는 여러 명의 [학생]이 소속됩니다. 하지만 한 명의 학생은 오직 하나의 반에만 소속됩니다.

반(SCHOOL_CLASS) 속성: 반번호(PK), 반이름
학생(STUDENT) 속성: 학번(PK), 학생이름, (어떤 외래키가 들어가야 할까요?)
👉 미션: 학생(N) 테이블을 생성하는 SQL문을 완성해 보세요! (반 테이블은 이미 만들어졌다고 가정합니다.)
*/